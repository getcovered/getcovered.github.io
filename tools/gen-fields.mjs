// Generates docs/FIELDS.md from the schema, so the docs can never drift from the code.
//   npm run docs
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { FIELDS } from '../assets/js/core/schema.js';

export function buildFieldsDoc() {
  const row = (cells) => `| ${cells.join(' | ')} |`;
  const code = (s) => `\`${String(s).replace(/\|/g, '\\|')}\``;

  const content = FIELDS.filter((f) => f.kind === 'content' || f.kind === 'virtual');
  const layout = FIELDS.filter((f) => f.kind === 'layout');
  const source = FIELDS.filter((f) => f.kind === 'source' || f.kind === 'meta');

  const lines = [
    '<!-- Generated by `npm run docs` from assets/js/core/schema.js. Do not edit by hand. -->',
    '',
    '# Field reference',
    '',
    'Every field a template can receive. The tests fail if a template does not render each',
    'field in the first table (or list it under `ignores` with a reason).',
    '',
    '## Fields a template must render',
    '',
    row(['Field', 'Applies to', 'What it is', 'How to render it', 'Shown when empty']),
    row(['---', '---', '---', '---', '---']),
    ...content.map((f) =>
      row([
        code(f.path),
        f.modes ? f.modes.join(' only') + ' only' : 'both modes',
        f.doc,
        code(f.use),
        f.dummy ? code(f.dummy) : (f.optional ? 'nothing (optional)' : '—'),
      ]),
    ),
    '',
    '## Layout fields — handled by the page engine',
    '',
    'You do not render these. The core applies them. Use the CSS variables where noted.',
    '',
    row(['Field', 'What it controls', 'Range or values']),
    row(['---', '---', '---']),
    ...layout.map((f) =>
      row([
        code(f.path),
        f.label,
        f.type === 'range'
          ? `${f.min} to ${f.max} ${f.unit}`
          : f.type === 'switch'
            ? 'on or off'
            : (f.options ?? []).map((o) => o.value).join(', '),
      ]),
    ),
    '',
    'CSS variables your template can use: `--gc-align` (left, center, right), `--gc-justify`',
    '(flex-start, center, flex-end), `--gc-logo-base` (set it to size the logo at 100%).',
    '',
    '## Fields that feed other fields',
    '',
    row(['Field', 'Purpose']),
    row(['---', '---']),
    ...source.map((f) => row([code(f.path), f.label])),
    '',
  ];
  return lines.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = new URL('../docs/FIELDS.md', import.meta.url);
  await writeFile(target, buildFieldsDoc());
  console.log('Wrote docs/FIELDS.md');
}
